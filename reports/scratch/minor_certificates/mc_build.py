"""Build, replay and record every minor certificate (independent code, mc_graph only).

For each claim: read G from the instance file, regenerate the contraction
sequence by the recorded heuristic, replay it step by step (each step must
contract a current edge), and compare the result with the minor recorded on
2026-10-11 in reports/scratch/pw_lower_bounds/ where one was recorded
(edge list or branch sets). Writes <claim>.json with the sequence, branch sets,
minor edges (labels 0..m-1 in increasing representative order) and its hash.

  python mc_build.py
"""
import json
from pathlib import Path
from mc_graph import (read_dgf, read_mosp_customer_graph, heuristic_sequence,
                      sequence_from_branch_sets, replay, relabel_sorted, edges, graph_hash)

ROOT = Path(__file__).resolve().parents[3]
OLD = ROOT / "reports/scratch/pw_lower_bounds"
OUT = Path(__file__).resolve().parent
COL = ROOT / "pathwidth_solver/bench/instances/coloring"
CS = ROOT / "benchmarks/instances/MOSP_Instances/Chu_Stuckey"

# name, graph loader, m, rule, claimed pw lower bound (pw(H) > w, w = bound - 1)
CLAIMS = [
    ("myciel6_m58", lambda: read_dgf(COL / "myciel6.dgf"), 58, "min-d", 38),
    ("myciel6_m60", lambda: read_dgf(COL / "myciel6.dgf"), 60, "min-d", 38),
    ("myciel7_m110", lambda: read_dgf(COL / "myciel7.dgf"), 110, "min-d", 71),
    ("Random-125-125-2-3_0_m70", lambda: read_mosp_customer_graph(CS / "Random-125-125-2-3.txt", "A"), 70, "least-c", 20),
    ("Random-125-125-2-1_0_m87", lambda: read_mosp_customer_graph(CS / "Random-125-125-2-1.txt", "A"), 87, "min-d", 23),
    ("Random-125-125-6-1_0_m120", lambda: read_mosp_customer_graph(CS / "Random-125-125-6-1.txt", "A"), 120, "min-d", 80),
    ("SP4_m96", lambda: read_mosp_customer_graph(ROOT / "benchmarks/instances/ChallengeInstances2005/Wilson/sp4.txt", "B", 3), 96, "min-d", 52),
]


def recorded(name, H, branch):
    """Compare with the 2026-10-11 record, if one exists. Returns a note."""
    Hs, idx = relabel_sorted(H)
    mine_sets = sorted(sorted(b) for b in branch.values())
    if name == "myciel6_m58":
        rec = sorted(tuple(sorted(e)) for e in json.load(open(OLD / "myciel6_minor58_edges.json")))
        assert rec == edges(Hs), "myciel6 m58 differs from recorded edge list"
        return "edge list equal to myciel6_minor58_edges.json (labels = sorted representatives)"
    if name == "myciel6_m60":
        rec = json.load(open(OLD / "myciel6_minor60.json"))
        rb = {int(k): set(v) for k, v in rec["branch_sets"].items()}
        assert rb == branch, "myciel6 m60 branch sets differ"
        re_ = sorted(tuple(sorted(e)) for e in rec["edges"])
        assert re_ == edges(H), "myciel6 m60 edges differ"
        return "branch sets and edge list equal to myciel6_minor60.json"
    files = {"myciel7_m110": "myciel7_minor110_branch_sets.json",
             "Random-125-125-2-3_0_m70": "Random-125-125-2-3_0_minor70_least-c.json",
             "Random-125-125-2-1_0_m87": "Random-125-125-2-1_0_minor87_min-d.json"}
    if name in files:
        rec = json.load(open(OLD / files[name]))
        rs = rec["branch_sets"] if isinstance(rec, dict) else rec
        assert sorted(sorted(b) for b in rs) == mine_sets, f"{name} branch sets differ"
        return f"branch sets equal to {files[name]}"
    return "no minor recorded on 2026-10-11; regenerated by the same rule"


def main():
    for name, load, m, rule, bound in CLAIMS:
        G = load()
        n, ne = len(G), sum(len(N) for N in G.values()) // 2
        seq = heuristic_sequence(G, m, rule)
        H, branch = replay(G, seq)
        assert len(H) == m
        note = recorded(name, H, branch)
        # second, independent route: a sequence derived from the branch sets alone
        seq2 = sequence_from_branch_sets(G, sorted(sorted(b) for b in branch.values()))
        H2, branch2 = replay(G, seq2)
        key = lambda Hx, bx: sorted(sorted((tuple(sorted(bx[a])), tuple(sorted(bx[b]))))
                                    for a in Hx for b in Hx[a] if a < b)
        assert key(H, branch) == key(H2, branch2), "the two contraction routes disagree"
        Hs, idx = relabel_sorted(H)
        cert = {"claim": f"pw(G) >= {bound}: pw(H) <= {bound - 1} is refuted on the minor H",
                "graph": name.rsplit("_m", 1)[0], "n": n, "edges_G": ne, "m": m, "rule": rule,
                "w": bound - 1,
                "contraction_sequence": [list(s) for s in seq],
                "contraction_sequence_note": "pairs [keep, absorbed] in G's labels; each step contracts a current edge",
                "branch_sets": sorted(sorted(b) for b in branch.values()),
                "minor_labels": sorted(H),
                "minor_edges": [list(e) for e in edges(Hs)],
                "minor_sha256": graph_hash(Hs),
                "comparison": note}
        json.dump(cert, open(OUT / f"{name}.json", "w"))
        json.dump([list(e) for e in edges(Hs)], open(OUT / f"{name}_edges.json", "w"))
        print(f"{name}: G n={n} e={ne} -> H m={m} e={len(edges(Hs))}; {len(seq)} contractions replayed; {note}; sha256 {graph_hash(Hs)[:16]}")


if __name__ == "__main__":
    main()
